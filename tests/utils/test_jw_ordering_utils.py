def test_validate_enumerations_raises_for_invalid_enumerations():
    """Check invalid enumerations are caught by checker function."""
    with pytest.raises(ValueError, match="Currently only 1 or 2 spin sectors supported."):
        # invalid enumeration with 0 spin sectors
        validate_enumerations([])

    with pytest.raises(ValueError, match="Currently only 1 or 2 spin sectors supported."):
        # invalid enumeration with 3 spin sectors
        validate_enumerations([np.array([[0]]), np.array([[1]]), np.array([[2]])])

    with pytest.raises(ValueError, match="All enumerations must have the same shape"):
        # invalid enumeration where different spin sectors have different shapes
        validate_enumerations([np.array([[0]]), np.array([[1, 2]])])

    with pytest.raises(ValueError, match="Duplicated indices found in enumerations."):
        # invalid enumeration with duplicated index in one spin sector
        validate_enumerations([np.array([[0, 0]])])

    with pytest.raises(ValueError, match="Duplicated indices found in enumerations."):
        # invalid enumeration with duplicated index across spin sectors
        validate_enumerations([np.array([[0]]), np.array([[0]])])


