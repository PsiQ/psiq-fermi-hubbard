def are_neighbors(plaq, enumeration):
    """Check if all values in the 2x2 plaquette come from a valid sub-block of the given enumeration."""
    for i in range(enumeration.shape[0] - 1):
        for j in range(enumeration.shape[1] - 1):
            block = enumeration[i : i + 2, j : j + 2]
            if np.array_equal(block, plaq):
                return True
    return False


@pytest.mark.parametrize("lattice_size", range(4, 22, 2))
@pytest.mark.parametrize("snaked", [True, False])
def test_get_plaqs_for_even_odd_enumeration(lattice_size, snaked):
    # Create simple test enumerations
    up = np.arange(lattice_size * lattice_size).reshape(lattice_size, lattice_size)
    down = np.arange(lattice_size * lattice_size, 2 * lattice_size * lattice_size).reshape(lattice_size, lattice_size)

    plaqs = get_plaqs([up, down], snaked=snaked)

    # --- Test 1: All values 0 to 2*L^2 - 1 appear exactly once ---
    all_values = np.sort(plaqs.flatten())
    expected_values = np.arange(2 * lattice_size * lattice_size)
    assert np.array_equal(all_values, expected_values), (
        f"Not all values from 0 to {2 * lattice_size * lattice_size - 1} appear exactly once. Missing: {set(expected_values) - set(all_values)}"
    )

    # --- Test 2: Each plaquette is from a valid 2x2 region in the original matrix ---
    half = len(plaqs) // 2
    up_plaqs = plaqs[:half]
    down_plaqs = plaqs[half:]

    for p in up_plaqs:
        assert are_neighbors(p, up), f"Up plaquette {p} is not a valid 2x2 block in up enumeration"

    for p in down_plaqs:
        assert are_neighbors(p, down), f"Down plaquette {p} is not a valid 2x2 block in down enumeration"
