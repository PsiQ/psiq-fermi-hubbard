def is_mod4_group(plaquette):
    """Check all 4 mod 4 values are unique (i.e., 0,1,2,3 in some order)."""
    mods = [x % 4 for x in plaquette.flatten()]
    return sorted(mods) == [0, 1, 2, 3]


def is_circular_ordered(plaquette):
    """Check if elements increase in a clockwise or anticlockwise order. Any other ordering would be incorrect."""
    a, b = plaquette[0, 0], plaquette[0, 1]
    d, c = plaquette[1, 0], plaquette[1, 1]

    clockwise = [b, c, d, a]
    anticlockwise = [a, d, c, b]

    return (clockwise == sorted(clockwise)) or (anticlockwise == sorted(anticlockwise))


