@pytest.mark.parametrize("lattice_size", [4, 12])
def test_generate_even_odd_enum_function(lattice_size):
    """Test generate_even_odd_enum function."""
    spin_up_enumeration, spin_down_enumeration = generate_even_odd_enum(lattice_size)

    # Check shape of enumeration is as expected
    assert spin_up_enumeration.shape == (
        lattice_size,
        lattice_size,
    ), f"Expected shape ({lattice_size}, {lattice_size}), got {spin_up_enumeration.shape}"
    assert spin_down_enumeration.shape == (
        lattice_size,
        lattice_size,
    ), f"Expected shape ({lattice_size}, {lattice_size}), got {spin_down_enumeration.shape}"

    # Check that the spin up enumeration contains all even indices as expected
    up_flattened = spin_up_enumeration.flatten()
    up_expected = np.arange(0, 2 * lattice_size * lattice_size, 2)
    assert np.array_equal(np.sort(up_flattened), up_expected), (
        f"Spin up enumeration does not contain all even integers from 0 to "
        f"{2 * lattice_size * lattice_size - 2} exactly once.\n"
        f"Got: {np.sort(up_flattened)}"
    )

    # Check that the spin down enumeration contains all odd indices as expected
    down_flattened = spin_down_enumeration.flatten()
    down_expected = np.arange(1, 2 * lattice_size * lattice_size, 2)
    assert np.array_equal(np.sort(down_flattened), down_expected), (
        f"Spin down enumeration does not contain all odd integers from 1 to "
        f"{2 * lattice_size * lattice_size - 1} exactly once.\n"
        f"Got: {np.sort(down_flattened)}"
    )


